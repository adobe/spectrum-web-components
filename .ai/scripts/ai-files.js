export const rel = (file) =>
  path.relative(ROOT, file).split(path.sep).join('/');

/**
 * Split a Markdown file into its YAML frontmatter text and body.
 * Returns `{ frontmatter: null, body }` when the file has no frontmatter.
 */
export function splitFrontmatter(source) {
  const match = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match) {
    return { frontmatter: null, body: source };
  }
  return { frontmatter: match[1], body: source.slice(match[0].length) };
}

/**
 * Read a Markdown file and parse its frontmatter.
 * Returns `{ file, rel, source, data, body, error }`; `data` is `null` without frontmatter.
 */
export function readMarkdown(file) {
  const source = readFileSync(file, 'utf8');
  const { frontmatter, body } = splitFrontmatter(source);
  let data = null;
  let error = null;
  if (frontmatter !== null) {
    try {
      data = parseYaml(frontmatter, { uniqueKeys: true }) ?? {};
      if (typeof data !== 'object' || Array.isArray(data)) {
        error = 'frontmatter must be a YAML mapping';
        data = null;
      }
    } catch (e) {
      error = `invalid YAML frontmatter: ${e.message.split('\n')[0]}`;
    }
  }
  return { file, rel: rel(file), source, data, body, error };
}

const markdownFilesIn = (dir) =>
  existsSync(dir)
    ? readdirSync(dir)
        .filter((f) => f.endsWith('.md'))
        .sort()
        .map((f) => path.join(dir, f))
    : [];

/**
 * Every instruction source. `kind` is `rule` or `memory`; `target` is the generated file stem.
 * Memory files without frontmatter are returned with `data: null` and are not generated.
 */
export function listInstructionSources() {
  const rules = markdownFilesIn(RULES_DIR).map((file) => ({
    kind: 'rule',
    name: path.basename(file, '.md'),
    target: path.basename(file, '.md'),
    ...readMarkdown(file),
  }));
  const memory = markdownFilesIn(MEMORY_DIR).map((file) => ({
    kind: 'memory',
    name: path.basename(file, '.md'),
    target: `memory-${path.basename(file, '.md')}`,
    ...readMarkdown(file),
  }));
  return [...rules, ...memory];
}

/**
 * Every `SKILL.md` under `.ai/skills/`, at any depth.
 * `dir` is the path relative to `.ai/skills/`; `depth` is the number of path segments.
 */
export function listSkills() {
  const found = [];
  const walk = (dir) => {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(full);
      } else if (entry.name === 'SKILL.md') {
        const dirRel = path.relative(SKILLS_DIR, dir).split(path.sep).join('/');
        found.push({
          dir: dirRel,
          dirName: path.basename(dir),
          depth: dirRel.split('/').length,
          ...readMarkdown(full),
        });
      }
    }
  };
  if (existsSync(SKILLS_DIR)) {
    walk(SKILLS_DIR);
  }
  return found.sort((a, b) => a.dir.localeCompare(b.dir));
}

let trackedCache = null;

/** Every file tracked by git, as repository-relative POSIX paths. */
export function trackedFiles() {
  if (!trackedCache) {
    trackedCache = execFileSync('git', ['ls-files', '-z'], {
      cwd: ROOT,
      encoding: 'utf8',
      maxBuffer: 256 * 1024 * 1024,
    })
      .split('\0')
      .filter(Boolean);
  }
  return trackedCache;
}

