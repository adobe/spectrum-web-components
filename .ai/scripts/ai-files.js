/**
 * Glob match with the semantics GitHub documents for `applyTo`: `*` stays within one
 * directory and `**` crosses directories.
 */
export const matchesGlob = (file, pattern) => path.matchesGlob(file, pattern);

/** Fails loudly if the glob engine ever drifts from GitHub's documented `applyTo` examples. */
export function assertGlobSemantics() {
  const cases = [
    ['a.css', '*.css', true],
    ['src/a.css', '*.css', false],
    ['src/a/b.css', '**/*.css', true],
    ['src/a.css', 'src/*.css', true],
    ['src/a/b.css', 'src/*.css', false],
    ['src/a/b/c.css', 'src/**/*.css', true],
  ];
  return cases
    .filter(([file, pattern, want]) => matchesGlob(file, pattern) !== want)
    .map(
      ([file, pattern, want]) =>
        `glob engine mismatch: matchesGlob('${file}', '${pattern}') should be ${want}`
    );
}

