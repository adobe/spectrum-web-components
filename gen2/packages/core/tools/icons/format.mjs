/**
 * "Do not edit" banner for a generated file, naming the command that produces it and the
 * source (folder or file, relative to the package root) to change instead.
 */
export function generatedBanner(command, source) {
  return `/* Generated by \`${command}\` from ${source}. Do not edit by hand. */`;
}

/**
 * PascalCase logical name to the kebab-case value used by the `icon` attribute (UI
 * icons) or the element tag suffix (workflow icons, `swc-icon-<kebab>`).
 *
 * Splits on two boundaries so digit-led acronyms kebab cleanly: an acronym-to-word
 * boundary (`3DAsset` -> `3D-Asset`, `HTMLParser` -> `HTML-Parser`) and a
 * lowercase-to-uppercase boundary (`AddCircle` -> `Add-Circle`). A digit immediately
 * before an uppercase letter is not a boundary, so `3D` stays `3d` rather than `3-d`.
 */
export function toKebab(name) {
  return name
    .replace(/([A-Z])([A-Z][a-z])/g, '$1-$2')
    .replace(/([a-z])([A-Z])/g, '$1-$2')
    .toLowerCase();
}
